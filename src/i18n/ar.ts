export function number(value: number, indic = false) {
  return new Intl.NumberFormat(indic ? 'ar-EG' : 'en-US', {
    maximumFractionDigits: 2,
  }).format(value);
}
export function money(
  value: number,
  settings: Pick<Settings, 'currency' | 'indic'>,
) {
  return `${number(value / 100, settings.indic)} ${settings.currency}`;
}
export function dateTime(value: number, timezone = 'Africa/Cairo') {
  return new Intl.DateTimeFormat('ar-EG-u-nu-latn', {
    dateStyle: 'short',
    timeStyle: 'short',
    timeZone: timezone,
  }).format(value);
}
export function dayKey(now: number, timezone = 'Africa/Cairo') {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: timezone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now);
}
export function duration(ms: number) {
  const seconds = Math.floor(Math.max(0, ms) / 1000);
  return `${Math.floor(seconds / 3600)
    .toString()
    .padStart(2, '0')}:${Math.floor((seconds / 60) % 60)
    .toString()
    .padStart(2, '0')}:${(seconds % 60).toString().padStart(2, '0')}`;
}
export function errorText(error: unknown) {
  const msg = error instanceof Error ? error.message : '';
  return (
    (
      {
        denied: ar.denied,
        'busy-room': ar.busyError,
        'clock-backwards': ar.clockError,
        'invalid-backup': ar.backupInvalid,
        'backup-version': ar.backupInvalid,
        'shift-required': ar.shiftRequired,
        'closed-shift': ar.closedError,
        'running-sessions': ar.closeBlocked,
        auth: ar.authError,
        future: ar.timeFuture,
      } as Record<string, string>
    )[msg] ?? ar.invalid
  );
}

